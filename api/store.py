"""SQLite store - spec section 10 tables.

Sync sqlite3 (check_same_thread=False); async callers wrap calls in threads.
Audit rows are written BEFORE execution and updated after (CodeReviewer finding 9).
"""
from __future__ import annotations

import base64
import json
import sqlite3
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

DEFAULT_DB_PATH = Path(__file__).resolve().parent / "data" / "assistant.db"

SCHEMA = """
CREATE TABLE IF NOT EXISTS conversations(
  id TEXT PRIMARY KEY, title TEXT, created_at TEXT
);
CREATE TABLE IF NOT EXISTS messages(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  conversation_id TEXT, role TEXT, content TEXT, created_at TEXT
);
CREATE TABLE IF NOT EXISTS pending_actions(
  id TEXT PRIMARY KEY, conversation_id TEXT, tool TEXT, args_json TEXT,
  args_hash TEXT, class TEXT, status TEXT, expires_at TEXT,
  contents_json TEXT, created_at TEXT
);
CREATE TABLE IF NOT EXISTS audit_log(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ts TEXT, tool TEXT, args_json TEXT, status TEXT, error TEXT, tasks_used INTEGER
);
CREATE TABLE IF NOT EXISTS usage(
  day TEXT PRIMARY KEY, model_calls INTEGER, mcp_tasks_month INTEGER
);
CREATE TABLE IF NOT EXISTS profile(key TEXT PRIMARY KEY, value TEXT);
"""

PENDING = "pending"
APPROVED = "approved"
REJECTED = "rejected"
EXECUTED = "executed"
EXPIRED = "expired"

APPROVAL_TTL_MINUTES = 10  # spec 6.2


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _iso(dt: datetime) -> str:
    return dt.isoformat()


_BYTES_MARKER = "__bytes_b64__"


def dump_contents(contents: list[Any]) -> str:
    """Serialize Content objects to JSON. gemini-3.x thought_signature values
    are bytes (M3.8) - encode them as base64 marker dicts so they round-trip."""
    def default(obj: object) -> object:
        if isinstance(obj, bytes):
            return {_BYTES_MARKER: base64.b64encode(obj).decode("ascii")}
        raise TypeError(f"Object of type {type(obj).__name__} is not JSON serializable")

    return json.dumps(
        [c.model_dump(exclude_none=True) for c in contents],
        ensure_ascii=False,
        default=default,
    )


def load_contents(contents_json: str) -> list[dict]:
    """Inverse of dump_contents: revive base64 marker dicts back to bytes."""
    def revive(obj: object) -> object:
        if isinstance(obj, dict):
            if len(obj) == 1 and _BYTES_MARKER in obj:
                return base64.b64decode(obj[_BYTES_MARKER])
            return {key: revive(value) for key, value in obj.items()}
        if isinstance(obj, list):
            return [revive(item) for item in obj]
        return obj

    return revive(json.loads(contents_json))


class Store:
    def __init__(self, db_path: Path | None = None) -> None:
        self._path = db_path or DEFAULT_DB_PATH
        self._path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = sqlite3.connect(self._path, check_same_thread=False)
        self._conn.row_factory = sqlite3.Row
        self._conn.executescript(SCHEMA)
        self._conn.commit()

    def close(self) -> None:
        self._conn.close()

    # ---- pending actions -------------------------------------------------

    def create_pending_action(
        self,
        *,
        pending_id: str,
        conversation_id: str,
        tool: str,
        args: dict,
        args_hash: str,
        classification: str,
        contents: list[Any],
        ttl_minutes: int = APPROVAL_TTL_MINUTES,
    ) -> str:
        """Persist a proposed action awaiting approval. Id is generated by the caller."""
        expires = _now() + timedelta(minutes=ttl_minutes)
        self._conn.execute(
            "INSERT INTO pending_actions(id, conversation_id, tool, args_json, args_hash,"
            " class, status, expires_at, contents_json, created_at)"
            " VALUES(?,?,?,?,?,?,?,?,?,?)",
            (
                pending_id,
                conversation_id,
                tool,
                json.dumps(args, ensure_ascii=False),
                args_hash,
                classification,
                PENDING,
                _iso(expires),
                dump_contents(contents),
                _iso(_now()),
            ),
        )
        self._conn.commit()
        return pending_id

    def get_pending_action(self, pending_id: str) -> dict | None:
        row = self._conn.execute(
            "SELECT * FROM pending_actions WHERE id = ?", (pending_id,)
        ).fetchone()
        return dict(row) if row else None

    def set_pending_status(
        self, pending_id: str, status: str, from_status: str = PENDING
    ) -> bool:
        """Status-guarded transition (M3.7: storage-level single-use).

        Default requires the row to be 'pending' (decisions: approve/reject/
        expire). The approve continuation passes from_status='approved' for
        the one-way resolution to executed/failed. Returns False when the row
        is not in the expected state - a zero-row UPDATE is what makes
        double-approve and double-resolve impossible.
        """
        cursor = self._conn.execute(
            "UPDATE pending_actions SET status = ? WHERE id = ? AND status = ?",
            (status, pending_id, from_status),
        )
        self._conn.commit()
        return cursor.rowcount > 0

    def update_pending_args(self, pending_id: str, args: dict, args_hash: str) -> bool:
        """Edit flow: replace args + hash; status stays pending."""
        cursor = self._conn.execute(
            "UPDATE pending_actions SET args_json = ?, args_hash = ? WHERE id = ?",
            (json.dumps(args, ensure_ascii=False), args_hash, pending_id),
        )
        self._conn.commit()
        return cursor.rowcount > 0

    def expire_stale(self) -> int:
        """Mark overdue pending actions as expired. Returns how many."""
        cursor = self._conn.execute(
            "UPDATE pending_actions SET status = ? WHERE status = ? AND expires_at < ?",
            (EXPIRED, PENDING, _iso(_now())),
        )
        self._conn.commit()
        return cursor.rowcount

    # ---- audit log ---------------------------------------------------------

    def audit(
        self, *, tool: str, args_json: str, status: str, error: str = "", tasks_used: int = 0
    ) -> None:
        self._conn.execute(
            "INSERT INTO audit_log(ts, tool, args_json, status, error, tasks_used)"
            " VALUES(?,?,?,?,?,?)",
            (_iso(_now()), tool, args_json, status, error, tasks_used),
        )
        self._conn.commit()

    def audit_entries(self, limit: int = 100) -> list[dict]:
        rows = self._conn.execute(
            "SELECT * FROM audit_log ORDER BY id DESC LIMIT ?", (limit,)
        ).fetchall()
        return [dict(row) for row in rows]

    # ---- usage counters ----------------------------------------------------

    def record_model_call(self) -> None:
        day = _now().date().isoformat()
        self._conn.execute(
            "INSERT INTO usage(day, model_calls, mcp_tasks_month) VALUES(?,1,0)"
            " ON CONFLICT(day) DO UPDATE SET model_calls = model_calls + 1",
            (day,),
        )
        self._conn.commit()

    def record_mcp_tasks(self, tasks: int) -> None:
        """Add to the month-to-date total, stored on every day row of this month."""
        month_prefix = _now().date().isoformat()[:7]
        self._conn.execute(
            "INSERT INTO usage(day, model_calls, mcp_tasks_month) VALUES(?,0,?)"
            " ON CONFLICT(day) DO UPDATE SET mcp_tasks_month = mcp_tasks_month + ?",
            (_now().date().isoformat(), tasks, tasks),
        )
        self._conn.execute(
            "UPDATE usage SET mcp_tasks_month = mcp_tasks_month + ?"
            " WHERE day LIKE ? AND day != ?",
            (tasks, month_prefix + "%", _now().date().isoformat()),
        )
        self._conn.commit()

    def usage_snapshot(self) -> dict:
        day = _now().date().isoformat()
        row = self._conn.execute(
            "SELECT model_calls, mcp_tasks_month FROM usage WHERE day = ?", (day,)
        ).fetchone()
        month_row = self._conn.execute(
            "SELECT mcp_tasks_month FROM usage WHERE day LIKE ?"
            " ORDER BY day DESC LIMIT 1",
            (day[:7] + "%",),
        ).fetchone()
        return {
            "day": day,
            "model_calls_today": row["model_calls"] if row else 0,
            "mcp_tasks_month": month_row["mcp_tasks_month"] if month_row else 0,
            "monthly_task_budget": 100,
        }
